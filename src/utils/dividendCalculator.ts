import { ShareAccount, Customer } from '../types';

export interface DividendProjectionParams {
  totalShareCapitalUGX: number;
  annualPerformanceRatePercent: number; // e.g. 12%
  statutoryReservePercent?: number; // e.g. 20% per Cooperatives Act
  withholdingTaxPercent?: number; // e.g. 15% statutory WHT
  shareAccounts: ShareAccount[];
  customers: Customer[];
}

export interface MemberDividendAllocation {
  accountId: string;
  accountNo: string;
  customerId: string;
  memberName: string;
  memberPhone: string;
  unitsHeld: number;
  shareCapitalUGX: number;
  ownershipPercent: number;
  grossDividendUGX: number;
  withholdingTaxUGX: number;
  netDividendUGX: number;
}

export interface DividendProjectionResult {
  totalShareCapitalUGX: number;
  totalUnitsHeld: number;
  annualPerformanceRatePercent: number;
  grossDividendPoolUGX: number;
  statutoryReservePercent: number;
  statutoryReserveUGX: number;
  distributableDividendPoolUGX: number;
  withholdingTaxPercent: number;
  totalWithholdingTaxUGX: number;
  netDividendPayoutUGX: number;
  dividendPerShareUnitUGX: number;
  effectiveNetYieldPercent: number;
  memberAllocations: MemberDividendAllocation[];
  varyingPerformanceScenarios: Array<{
    ratePercent: number;
    grossPoolUGX: number;
    distributablePoolUGX: number;
    netPayoutUGX: number;
    dividendPerShareUGX: number;
  }>;
}

/**
 * Calculates projected dividend payouts based on share capital balance,
 * statutory reserves, withholding taxes, and varying performance percentages.
 */
export function calculateDividendProjection(params: DividendProjectionParams): DividendProjectionResult {
  const {
    totalShareCapitalUGX,
    annualPerformanceRatePercent,
    statutoryReservePercent = 20,
    withholdingTaxPercent = 15,
    shareAccounts = [],
    customers = [],
  } = params;

  const validCapital = Math.max(0, totalShareCapitalUGX);
  const validRate = Math.max(0, annualPerformanceRatePercent);
  const totalUnitsHeld = shareAccounts.reduce((sum, s) => sum + (s.unitsHeld || 0), 0);

  // Gross pool generated by performance return rate
  const grossDividendPoolUGX = Math.round((validCapital * validRate) / 100);

  // Mandatory statutory reserve retention
  const statutoryReserveUGX = Math.round((grossDividendPoolUGX * Math.max(0, statutoryReservePercent)) / 100);

  // Distributable dividend pool to shareholders
  const distributableDividendPoolUGX = Math.max(0, grossDividendPoolUGX - statutoryReserveUGX);

  // Statutory withholding tax
  const totalWithholdingTaxUGX = Math.round((distributableDividendPoolUGX * Math.max(0, withholdingTaxPercent)) / 100);

  // Net cash payout to shareholders
  const netDividendPayoutUGX = Math.max(0, distributableDividendPoolUGX - totalWithholdingTaxUGX);

  // Dividend per unit
  const dividendPerShareUnitUGX = totalUnitsHeld > 0 ? Math.round(distributableDividendPoolUGX / totalUnitsHeld) : 0;

  // Effective net yield %
  const effectiveNetYieldPercent = validCapital > 0 ? Number(((netDividendPayoutUGX / validCapital) * 100).toFixed(2)) : 0;

  // Member-level allocations
  const memberAllocations: MemberDividendAllocation[] = shareAccounts.map((account) => {
    const cust = customers.find((c) => c.id === account.customerId);
    const units = account.unitsHeld || 0;
    const ownershipPercent = totalUnitsHeld > 0 ? Number(((units / totalUnitsHeld) * 100).toFixed(2)) : 0;
    
    // Pro-rata gross dividend based on units
    const grossDiv = totalUnitsHeld > 0 ? Math.round((units / totalUnitsHeld) * distributableDividendPoolUGX) : 0;
    const wht = Math.round((grossDiv * Math.max(0, withholdingTaxPercent)) / 100);
    const netDiv = Math.max(0, grossDiv - wht);

    return {
      accountId: account.id,
      accountNo: account.accountNo,
      customerId: account.customerId,
      memberName: cust?.fullName || 'SACCO Member',
      memberPhone: cust?.phone || 'N/A',
      unitsHeld: units,
      shareCapitalUGX: account.totalValueUGX,
      ownershipPercent,
      grossDividendUGX: grossDiv,
      withholdingTaxUGX: wht,
      netDividendUGX: netDiv,
    };
  });

  // Varying performance scenarios (e.g. 5%, 8%, 10%, 12%, 15%, 20%)
  const benchmarkRates = [5, 8, 10, 12, 15, 18, 20];
  const varyingPerformanceScenarios = benchmarkRates.map((rate) => {
    const gross = Math.round((validCapital * rate) / 100);
    const reserve = Math.round((gross * Math.max(0, statutoryReservePercent)) / 100);
    const distributable = Math.max(0, gross - reserve);
    const tax = Math.round((distributable * Math.max(0, withholdingTaxPercent)) / 100);
    const net = Math.max(0, distributable - tax);
    const perShare = totalUnitsHeld > 0 ? Math.round(distributable / totalUnitsHeld) : 0;

    return {
      ratePercent: rate,
      grossPoolUGX: gross,
      distributablePoolUGX: distributable,
      netPayoutUGX: net,
      dividendPerShareUGX: perShare,
    };
  });

  return {
    totalShareCapitalUGX: validCapital,
    totalUnitsHeld,
    annualPerformanceRatePercent: validRate,
    grossDividendPoolUGX,
    statutoryReservePercent,
    statutoryReserveUGX,
    distributableDividendPoolUGX,
    withholdingTaxPercent,
    totalWithholdingTaxUGX,
    netDividendPayoutUGX,
    dividendPerShareUnitUGX,
    effectiveNetYieldPercent,
    memberAllocations,
    varyingPerformanceScenarios,
  };
}

/**
 * Generates RFC 4180 compliant CSV string for dividend distribution schedule
 */
export function exportDividendScheduleCSV(result: DividendProjectionResult, tenantName: string): string {
  const header = ['Account No', 'Member Name', 'Phone', 'Units Held', 'Share Capital (UGX)', 'Ownership %', 'Gross Dividend (UGX)', 'Withholding Tax (UGX)', 'Net Dividend Payout (UGX)'];
  const rows = result.memberAllocations.map((m) => [
    `"${m.accountNo}"`,
    `"${m.memberName.replace(/"/g, '""')}"`,
    `"${m.memberPhone}"`,
    m.unitsHeld,
    m.shareCapitalUGX,
    `${m.ownershipPercent}%`,
    m.grossDividendUGX,
    m.withholdingTaxUGX,
    m.netDividendUGX,
  ]);

  const summary = [
    [],
    [`"--- Dividend Model Summary: ${tenantName} ---"`],
    [`"Total Share Capital:"`, `"${result.totalShareCapitalUGX} UGX"`],
    [`"Performance Rate:"`, `"${result.annualPerformanceRatePercent}%"`],
    [`"Gross Dividend Pool:"`, `"${result.grossDividendPoolUGX} UGX"`],
    [`"Statutory Reserve (${result.statutoryReservePercent}%):"`, `"${result.statutoryReserveUGX} UGX"`],
    [`"Distributable Pool:"`, `"${result.distributableDividendPoolUGX} UGX"`],
    [`"Withholding Tax (${result.withholdingTaxPercent}%):"`, `"${result.totalWithholdingTaxUGX} UGX"`],
    [`"Net Cash Payout:"`, `"${result.netDividendPayoutUGX} UGX"`],
    [`"Dividend Per Unit:"`, `"${result.dividendPerShareUnitUGX} UGX"`],
  ];

  const allLines = [header.join(','), ...rows.map((r) => r.join(',')), ...summary.map((s) => s.join(','))];
  return '\uFEFF' + allLines.join('\r\n');
}
